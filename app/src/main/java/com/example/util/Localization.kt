fun getAppStrings(language: String): AppStrings {
    val clean = language.trim()
    return when {
        clean.equals("TE", ignoreCase = true) || clean.contains("Telugu", ignoreCase = true) || clean.contains("తెలుగు") -> TeluguStrings
        clean.equals("HI", ignoreCase = true) || clean.contains("Hindi", ignoreCase = true) || clean.contains("हिन्दी") -> HindiStrings
        clean.equals("KN", ignoreCase = true) || clean.contains("Kannada", ignoreCase = true) || clean.contains("ಕನ್ನಡ") -> KannadaStrings
        clean.equals("TA", ignoreCase = true) || clean.contains("Tamil", ignoreCase = true) || clean.contains("தமிழ்") -> TamilStrings
        clean.equals("ML", ignoreCase = true) || clean.contains("Malayalam", ignoreCase = true) || clean.contains("മലയാളം") -> MalayalamStrings
        clean.equals("MR", ignoreCase = true) || clean.contains("Marathi", ignoreCase = true) || clean.contains("मराठी") -> MarathiStrings
        clean.equals("BN", ignoreCase = true) || clean.contains("Bengali", ignoreCase = true) || clean.contains("বাংলা") -> BengaliStrings
        clean.equals("GU", ignoreCase = true) || clean.contains("Gujarati", ignoreCase = true) || clean.contains("ગુજરાતી") -> GujaratiStrings
        else -> EnglishStrings
    }
}

